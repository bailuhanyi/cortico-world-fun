const QUOTE = (s) => `      '${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}',`;
const RARE_QUOTE = (s) => `      '${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}',`;

/** 找到某个 venue 对象里 `randomEvents: [` 对应数组的收尾位置。 */
function findBlock(src, id) {
  const idAt = src.indexOf(`id: '${id}'`);
  if (idAt < 0) return null;
  const evAt = src.indexOf('randomEvents: [', idAt);
  if (evAt < 0) return null;
  // 从 randomEvents 的 `[` 开始配平中括号，找到它自己的 `]`。
  let depth = 0;
  let i = src.indexOf('[', evAt);
  for (; i < src.length; i += 1) {
    if (src[i] === '[') depth += 1;
    else if (src[i] === ']') {
      depth -= 1;
      if (depth === 0) break;
    }
  }
  if (depth !== 0) return null;
  return { idAt, evAt, closeAt: i };
}

const dry = !process.argv.includes('--write');
let src = await readFile(FILE, 'utf8');

let changed = 0;
const report = [];
const problems = [];

/**
 * 一次改一处，改完重新扫（因为偏移会变）。
 *
 * 插入点是 `randomEvents` 数组自己的收尾 `]` **之前**（补常见）
 * 以及那个 `]` 之后（接 `rareEvents`）。不碰任何原有行，只做加法。
 */
for (const [id, add] of Object.entries(ADD)) {
  const block = findBlock(src, id);
  if (!block) { problems.push(`${id}：找不到 randomEvents 块`); continue; }
  if (src.slice(block.evAt, block.closeAt).includes('rareEvents')) {
    report.push(`  = ${id} 已经有 rareEvents，跳过`);
    continue;
  }
  report.push(`  + ${id}：常见 +${add.common.length}，少见 +${add.rare.length}`);
  changed += 1;
  if (dry) continue;

  const common = add.common.map(QUOTE).join('\n');
  const rare = add.rare.map(RARE_QUOTE).join('\n');
  // 收尾 `]` 之前补常见项；之后接 rareEvents。原有内容一个字不动。
  const head = src.slice(0, block.closeAt);
  const tail = src.slice(block.closeAt + 1);   // 跳过 `]`
  src = `${head}\n${common}\n    ],\n    rareEvents: [\n${rare}\n    ],${tail.replace(/^,/, '')}`;
}

console.log(report.join('\n'));
if (problems.length) {
  console.error('\n有问题：\n' + problems.join('\n'));
  process.exit(1);
}
console.log(`\n${dry ? '预演' : '已写'}：${changed} 处${dry ? '需要改（加 --write 真写）' : ''}`);

if (!dry && changed) {
  await writeFile(FILE, src, 'utf8');
  console.log(`已写入 ${FILE}`);
}
